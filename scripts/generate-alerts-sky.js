#!/usr/bin/env node
'use strict';
/*
 * Writes alerts/src/sky.js: the clear-and-dark score, copied out of
 * index.html so the alerts Worker scores tonight exactly as the Console does.
 *
 * Copied rather than rewritten: a hand port is a second implementation that
 * drifts (twilight-calc.js needs solar-parity.test.js for that reason). This
 * copies the shipped declarations verbatim, and alerts.test.js fails if the
 * committed file no longer matches what this script would write now, so a
 * change to the score in index.html can't reach the Console and not the alerts.
 *
 *   node scripts/generate-alerts-sky.js
 */
const fs = require('fs');
const path = require('path');
const { declSource } = require('./test/extract.js');

const NAMES = ['D2R', 'R2D', 'rev', 'sin', 'cos', 'asin', 'atan2', 'acos', 'jd', 'gmst',
  'sunRaDec', 'sunHcZn', 'sunAltitude', 'MOON_LR', 'MOON_B', 'moonEcliptic', 'moonState', 'scoreHours', 'summarize', 'clearDarkScore'];
const EXPORTS = ['sunAltitude', 'moonState', 'clearDarkScore'];
const OUT = path.join(__dirname, '..', 'alerts', 'src', 'sky.js');

function build() {
  const seen = new Set();
  const parts = [];
  for (const n of NAMES) {
    const s = declSource(n);
    if (!seen.has(s)) { seen.add(s); parts.push(s); }
  }
  return '// GENERATED by scripts/generate-alerts-sky.js from index.html. Do not edit:\n' +
    '// change index.html and re-run the script. alerts.test.js checks it is current.\n\n' +
    parts.join('\n') + '\n\nexport { ' + EXPORTS.join(', ') + ' };\n';
}

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log('wrote ' + path.relative(process.cwd(), OUT));
}

module.exports = { build, OUT };
